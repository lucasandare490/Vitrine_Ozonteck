import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const env = await fs.readFile('.env', 'utf8');
const base = new URL(env.match(/^NEXT_PUBLIC_SUPABASE_URL\s*=\s*["']?([^\s"']+)/m)[1]);
const user = { id: '20000000-0000-0000-0000-000000000001', email: 'qa@example.invalid', factors: [], aud: 'authenticated', role: 'authenticated', user_metadata: {} };
const exp = Math.floor(Date.now() / 1000) + 3600;
const token = [{ alg: 'HS256', typ: 'JWT' }, { sub: user.id, exp, role: 'authenticated', aal: 'aal1' }].map(v => Buffer.from(JSON.stringify(v)).toString('base64url')).join('.') + '.fixture';
const id = 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  for (const width of [390, 1440]) {
    let paid = false;
    let boleto = false;
    const context = await browser.newContext({ viewport: { width, height: 900 } });
    await context.addInitScript(({ key, session }) => localStorage.setItem(key, JSON.stringify(session)), { key: `sb-${base.hostname.split('.')[0]}-auth-token`, session: { access_token: token, refresh_token: 'fixture', expires_at: exp, expires_in: 3600, token_type: 'bearer', user } });
    await context.route('**/api/checkout', () => { throw new Error('No charges allowed'); });
    await context.route(`${base.origin}/**`, route => {
      const path = new URL(route.request().url()).pathname;
      let data = [];
      if (path.startsWith('/auth/')) data = user;
      else if (path.endsWith('/profiles')) data = { id: user.id, nome: 'Cliente QA', role: 'cliente', carrinho: [] };
      else if (path.endsWith('/pedido_alteracoes')) data = { id: '10000000-0000-4000-8000-000000000002', novo_pedido_id: null, antes: { itens: [{ code: 'TESTE-001', nome: 'Produto teste', qtd: 1, preco_unitario: 9.99 }], endereco: { nome: 'Cliente QA', telefone: '81999999999', rua: 'Rua de teste', numero: '123', cep: '50050015', cidade: 'Recife', estado: 'PE', bairro: 'Boa Vista', modalidade: 'entrega' } } };
      else if (path.endsWith('/rpc/my_store_prices')) data = { enabled: false, prices: {} };
      else if (path.endsWith('/pedidos')) data = [{ id, status: paid ? 'preparando' : 'pending', valor_total: 9.99, itens: [], endereco_entrega: { modalidade: 'retirada' }, created_at: new Date().toISOString() }];
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify(data) });
    });
    await context.route('**/api/pedidos/*/pagamento', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ orderId: id, orderStatus: paid ? 'preparando' : 'pendente', status: paid ? 'approved' : 'pending', amount: 9.99, method: boleto ? 'bolbradesco' : 'pix', type: boleto ? 'ticket' : 'bank_transfer', expiresAt: null, expired: false, payable: !paid, pixCode: !paid && !boleto ? 'fixture-pix' : null, boletoCode: !paid && boleto ? 'fixture-boleto' : null, boletoUrl: !paid && boleto ? 'https://www.mercadopago.com.br/boleto' : null }) }));
    const page = await context.newPage(); page.setDefaultTimeout(30000);
    await page.goto('http://localhost:3013/conta/pedidos', { timeout: 120000, waitUntil: 'domcontentloaded' });
    await page.getByRole('button', { name: 'Pagamentos em aberto', exact: true }).click();
    await page.getByRole('button', { name: 'Ver pagamento e detalhes' }).click();
    await page.getByRole('button', { name: 'Copiar código Pix' }).waitFor();
    await page.reload({ waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.getByRole('button', { name: 'Pagamentos em aberto', exact: true }).click();
    await page.getByRole('button', { name: 'Ver pagamento e detalhes' }).click();
    await page.getByRole('button', { name: 'Copiar código Pix' }).waitFor();
    boleto = true;
    await page.getByRole('button', { name: 'Atualizar pagamento' }).click();
    await page.getByRole('link', { name: 'Abrir boleto' }).waitFor();
    await page.screenshot({ path: `sandbox-runtime/order-payment-${width}.png`, fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    paid = true;
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await page.getByRole('button', { name: 'Pedidos confirmados', exact: true }).click();
    await page.getByRole('heading', { name: 'Pagamento aprovado' }).waitFor();
    assert.equal(await page.getByRole('link', { name: 'Abrir boleto' }).count(), 0);
    await page.goto('http://localhost:3013/lista', { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.getByRole('button', { name: 'Prévia do pedido confirmado' }).click();
    await page.getByRole('heading', { name: 'Pedido confirmado', exact: true }).waitFor();
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.screenshot({ path: `sandbox-runtime/order-preview-${width}.png` });
    await page.getByRole('button', { name: 'Voltar à compra real' }).click();
    await page.getByRole('heading', { name: 'Checkout Seguro' }).waitFor();
    paid = false;
    await context.route('**/api/pedidos/*/alterar', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ change: { id: '10000000-0000-4000-8000-000000000002' } }) }));
    await page.goto('http://localhost:3013/conta/pedidos', { waitUntil: 'domcontentloaded', timeout: 120000 });
    await page.getByRole('button', { name: 'Pagamentos em aberto', exact: true }).click();
    await page.getByRole('button', { name: 'Ver pagamento e detalhes' }).click();
    await page.getByRole('button', { name: 'Alterar endereço', exact: true }).click();
    await page.getByRole('button', { name: 'Cancelar cobrança e editar', exact: true }).click();
    await page.waitForURL('**/lista?alteracao=*');
    await page.locator('input[name="street"]').waitFor();
    assert.equal(await page.locator('input[name="street"]').inputValue(), 'Rua de teste');
    await page.screenshot({ path: `sandbox-runtime/order-edit-${width}.png`, fullPage: true });
    assert.equal(await page.getByRole('dialog').count(), 0);
    await context.close();
    console.log(`PASS ${width}: reopen after reload, Pix/boleto, approved refresh, no overflow; mocked services, no charges.`);
  }
} finally { await browser.close(); }
