import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const owner='00000000-0000-0000-0000-000000000001', other='00000000-0000-0000-0000-000000000002', ticket='00000000-0000-0000-0000-000000000003';
try {
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
    create table auth.users(id uuid primary key,email_confirmed_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('app.uid',true),'')::uuid$$;
    create function public.is_admin() returns boolean language sql stable as $$select coalesce(current_setting('app.admin',true),'false')='true'$$;
    create function public.account_mfa_allowed() returns boolean language sql stable as $$select coalesce(current_setting('app.mfa',true),'true')='true'$$;
    create table pedidos(id uuid primary key,user_id uuid,status text,status_pagamento text,id_pagamento_mp text);
    create table pedido_alteracoes(id uuid primary key,user_id uuid,novo_pedido_id uuid);
    grant usage on schema public,auth to authenticated; grant execute on all functions in schema public,auth to authenticated;`);
  await db.exec(await readFile('supabase/migrations/202611010001_customer_email_outbox.sql','utf8'));
  await db.exec(await readFile('supabase/migrations/202611040004_support_tickets.sql','utf8'));
  await db.query('insert into auth.users values($1,null),($2,null)',[owner,other]);
  await db.exec(`set role authenticated; set app.uid='${owner}';`);
  await db.query('select open_support_ticket($1,$2,$3)',[ticket,'Ajuda com pedido','Preciso de ajuda com minha compra.']);
  await db.query('select open_support_ticket($1,$2,$3)',[ticket,'Ajuda com pedido','Preciso de ajuda com minha compra.']);
  assert.equal((await db.query('select count(*)::int as n from support_tickets')).rows[0].n,1);
  await assert.rejects(db.query('update support_tickets set response=$1',['forjado']));
  await assert.rejects(db.query('select respond_support_ticket($1,$2,$3)',[ticket,'Resposta','respondido']));
  await db.exec(`set app.uid='${other}';`);
  assert.equal((await db.query('select * from support_tickets')).rows.length,0);
  await assert.rejects(db.query('select open_support_ticket($1,$2,$3)',[ticket,'Ajuda com pedido','Preciso de ajuda com minha compra.']));
  await db.exec(`set app.uid='${owner}'; set app.admin='true'; set app.mfa='false';`);
  await assert.rejects(db.query('select respond_support_ticket($1,$2,$3)',[ticket,'Resposta','respondido']));
  await db.exec("set app.mfa='true';");
  await db.query('select respond_support_ticket($1,$2,$3)',[ticket,'Atendimento concluído','resolvido']);
  await db.query('select respond_support_ticket($1,$2,$3)',[ticket,'Atendimento concluído','resolvido']);
  assert.equal((await db.query('select status from support_tickets')).rows[0].status,'resolvido');
  await db.exec('reset role');
  assert.deepEqual((await db.query('select event from customer_email_outbox order by created_at')).rows.map(x=>x.event),['support_received','support_updated']);
  await db.exec(`set role authenticated; set app.admin='false';`);
  for(let i=0;i<4;i++) await db.query('select open_support_ticket(gen_random_uuid(),$1,$2)',['Outro assunto','Mensagem suficientemente longa.']);
  await assert.rejects(db.query('select open_support_ticket(gen_random_uuid(),$1,$2)',['Limite atingido','Mensagem suficientemente longa.']), /SUPPORT_LIMIT/);
  console.log('Support: ownership/RLS, MFA, admin-only replies, deduplication, persistent responses and daily limit passed.');
} finally { await db.close(); }
