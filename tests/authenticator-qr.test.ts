import assert from 'node:assert/strict';
import test from 'node:test';
import { createRequire } from 'node:module';
import { encodeAuthenticatorQr } from '../lib/authenticator-qr.ts';

const require = createRequire(import.meta.url);
const { getImageProps } = require('next/image');

test('preserves the complete Supabase SVG, including XML header, colors and trailing newline', () => {
  const svg = '<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg" width="231" height="231">\n<rect width="3" height="3" fill="#000" />\n</svg>\n';
  const raw = `data:image/svg+xml;utf-8,${svg}`;
  assert.throws(() => getImageProps({ src: raw, width: 200, height: 200, alt: 'QR', unoptimized: true }), /control character/);
  const src = encodeAuthenticatorQr(raw);
  assert.equal(decodeURIComponent(src.slice(src.indexOf(',') + 1)), svg);
  assert.equal(/[\r\n#]/.test(src), false);
  assert.equal(getImageProps({ src, width: 200, height: 200, alt: 'QR', unoptimized: true }).props.src, src);
});

test('rejects unexpected URLs instead of sending an authentication QR to another server', () => {
  assert.throws(() => encodeAuthenticatorQr('https://example.com/qr'));
});
